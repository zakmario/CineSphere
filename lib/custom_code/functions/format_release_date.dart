/// Formate une date en français : "16 juillet 2010".
String formatReleaseDate(DateTime? date) {
  if (date == null) {
    return 'Date inconnue';
  }
  const months = [
    'janvier',
    'février',
    'mars',
    'avril',
    'mai',
    'juin',
    'juillet',
    'août',
    'septembre',
    'octobre',
    'novembre',
    'décembre',
  ];
  return '${date.day} ${months[date.month - 1]} ${date.year}';
}
