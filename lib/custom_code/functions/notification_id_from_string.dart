/// Identifiant de notification stable (entier 31 bits) dérivé d'une chaîne,
/// ex.
///
/// l'id d'un release_event. String.hashCode n'est pas garanti stable entre
/// deux lancements, d'où ce hash FNV-1a.
int notificationIdFromString(String key) {
  var hash = 0x811c9dc5;
  for (final unit in key.codeUnits) {
    hash ^= unit;
    hash = (hash * 0x01000193) & 0xFFFFFFFF;
  }
  return hash & 0x7FFFFFFF;
}
